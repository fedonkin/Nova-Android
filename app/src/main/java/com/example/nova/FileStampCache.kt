package com.example.nova

/**
 * Отметка файла: длина и время изменения.
 *
 * Обе величины вместе отвечают на вопрос «тот ли это файл, что мы читали» и стоят
 * два вызова `stat`, то есть на два порядка дешевле чтения и разбора JSON.
 */
data class FileStamp(
    val length: Long,
    val modifiedAtMs: Long,
)

/**
 * Значение, прочитанное из файла, вместе с отметкой, при которой оно прочитано.
 *
 * ## Зачем
 *
 * Экран спрашивает состояние службы по нескольку раз за один такт: снимок экрана
 * берёт четыре поля по отдельности ([com.example.nova.ClientData.getServiceState],
 * `getServiceBackend`, `getServiceAttemptOrdinal`, `getServiceAttemptTotal`), ещё
 * по разу его спрашивают проверки живости и расчёт задержки следующего опроса.
 * Каждый вопрос раньше читал `service_state.json` целиком и разбирал JSON заново —
 * на главном потоке, раз в секунду, пока идёт подключение. То же у файла перебора
 * точек входа: его читает каждый такт, а меняется он раз в несколько секунд.
 *
 * ## Как держится свежесть
 *
 *  * **Отметка файла.** Не изменилась отметка — не изменился и текст: файлы пишутся
 *    атомарной подменой (`AtomicFile`), а не правкой на месте.
 *  * **Своя запись** сбрасывает кэш явно ([invalidate]), не надеясь на отметку.
 *  * **Срок жизни** ([maxAgeMs]). Отметка говорит правду только настолько, насколько
 *    точны часы файловой системы: `lastModified` отдаёт миллисекунды, а состояния
 *    `CONNECTING` и `CONNECTED` — одной длины, и запись «в ту же миллисекунду»
 *    оставила бы в кэше прошлое состояние до следующей записи. Поэтому запомненное
 *    живёт не дольше срока, даже если отметка не менялась.
 *
 * Отметка снимается **до** и **после** чтения: если файл подменили, пока мы его
 * читали, отметки разойдутся и прочитанное не запомнится — иначе в кэш попал бы
 * огрызок, помеченный как свежий.
 *
 * Нет отметки (файла нет, он пуст, `stat` не удался) — значения не запоминаются
 * вовсе: у пустого файла читатель обязан спросить резервную копию и настройки, а
 * они меняются без всякой отметки.
 *
 * Класс без зависимостей от Android: его проверяют обычные unit-тесты.
 */
class FileStampCache<T>(
    private val read: () -> T,
    private val stamp: () -> FileStamp?,
    /** Сколько запомненное живёт, даже если отметка не менялась. */
    private val maxAgeMs: Long = Long.MAX_VALUE,
    private val now: () -> Long = { System.currentTimeMillis() },
) {

    /**
     * Прочитанное значение вместе с тем, при какой отметке оно прочитано.
     *
     * Отдельным классом, а не парой полей: значение может быть и `null` (у файла
     * нет снимка перебора), и тогда «прочитали и ничего нет» отличается от
     * «ещё не читали» только наличием самой записи.
     */
    private class Entry<T>(val value: T, val stamp: FileStamp, val atMs: Long)

    private var entry: Entry<T>? = null

    /**
     * Значение по текущей отметке файла.
     *
     * Чтение идёт вне замка: два потока, попавшие сюда разом, просто прочитают
     * файл дважды — это то же, что было до кэша. Замок держит только запись
     * результата, и держит её коротко.
     */
    fun get(): T {
        val before = stamp()
        val askAtMs = now()
        synchronized(this) {
            val cached = entry
            if (
                cached != null &&
                before != null &&
                cached.stamp == before &&
                askAtMs - cached.atMs < maxAgeMs
            ) {
                return cached.value
            }
        }
        val fresh = read()
        synchronized(this) {
            // Файл подменили во время чтения — прочитанное может быть смесью двух
            // записей: отвечаем им, но не запоминаем.
            val after = stamp()
            entry = if (after != null && after == before) Entry(fresh, after, now()) else null
        }
        return fresh
    }

    /** Забыть прочитанное: своя запись в этот файл. */
    fun invalidate() {
        synchronized(this) {
            entry = null
        }
    }
}
