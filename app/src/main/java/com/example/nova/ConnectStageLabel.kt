package com.example.nova

/**
 * Названия этапов подключения для экрана.
 *
 * Этапы приходят из службы теми же словами, что пишутся в журнал
 * ([ConnectTimeline]): «транспорт», «ядро», «рукопожатие», «проба». В журнале они
 * стоят рядом с миллисекундами и читаются специалистом; на экране нужны короткие
 * слова, которые объясняют человеку, чего он ждёт прямо сейчас.
 *
 * Незнакомый этап молчит намеренно: служба может добавить новый шаг раньше, чем
 * экран научится его называть, и показывать сырой ключ вроде «masque-bootstrap»
 * хуже, чем не показывать ничего.
 */
object ConnectStageLabel {

    /** Этап подготовки транспорта: снятие прежнего движка, чистое состояние. */
    const val STAGE_TRANSPORT = "транспорт"

    /** Создание TUN-интерфейса. */
    const val STAGE_INTERFACE = "интерфейс"

    /** Вызов старта движка. */
    const val STAGE_CORE = "ядро"

    /** Возврат из старта движка: ядро поднялось и начало работать. */
    const val STAGE_ENGINE = "движок"

    /** Первое рукопожатие с узлом. */
    const val STAGE_HANDSHAKE = "рукопожатие"

    /** Сквозная проверка туннеля. */
    const val STAGE_PROBE = "проба"

    /**
     * @param stage ключ этапа из службы.
     * @return короткая подпись для экрана; пустая строка — этап не показываем.
     */
    fun label(stage: String): String = when (stage.trim().lowercase()) {
        STAGE_TRANSPORT -> "сеть"
        STAGE_INTERFACE -> "интерфейс"
        // «ядро» и «движок» — один и тот же шаг для человека: старт движка и
        // возврат из него. В журнале их два (по ним видно, сколько стоит сам
        // вызов), на экране — одно слово.
        STAGE_CORE -> "ядро"
        STAGE_ENGINE -> "ядро"
        STAGE_HANDSHAKE -> "рукопожатие"
        STAGE_PROBE -> "проверка"
        else -> ""
    }
}
