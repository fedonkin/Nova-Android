package com.example.nova

/**
 * Сколько уже идёт подключение — для надписи на главном экране.
 *
 * Зачем. Подключение занимает от двух до двадцати секунд, и всё это время
 * подпись не менялась: «ПОДКЛЮЧЕНИЕ... AUTO» стояла на месте, пока человек уже
 * решал, не зависло ли приложение. Точка, которая просто не двигается, выглядит
 * поломкой, даже когда всё идёт по плану.
 *
 * Что показывает. Секунды от начала попытки, обновляемые тем же опросом
 * состояния, который на экране и так идёт. Второй таймер на экране не заводится:
 * лишний `postDelayed` будил бы экран ради одной цифры.
 *
 * Чего не делает. Не знает ни про этапы подключения, ни про причины отказа — это
 * дело [ConnectTimeline] и журнала. Здесь только арифметика «сколько прошло», и
 * она вынесена отдельно, чтобы её можно было проверить тестом: экранный код
 * тестами не покрыт.
 */
object ConnectElapsed {

    /** Меньше секунды не показываем: «0 с» — это шум, а не информация. */
    const val MIN_VISIBLE_MS = 1_000L

    /**
     * Потолок показываемого: через двадцать минут ожидания число перестаёт быть
     * подсказкой, а трёхзначное «1200» ещё и разъезжается по ширине. Дальше
     * показываем 999 — «очень долго» читается и так.
     */
    const val MAX_SHOWN_SECONDS = 999L

    /**
     * @param startedAtMs когда началась попытка, по `elapsedRealtime`; 0 или
     *   меньше — подключения нет.
     * @param nowMs текущее `elapsedRealtime`.
     * @return целые секунды ожидания или `null`, если показывать нечего.
     */
    fun secondsOrNull(startedAtMs: Long, nowMs: Long): Long? {
        if (startedAtMs <= 0L) return null
        val elapsedMs = nowMs - startedAtMs
        // Отрицательная разница — не «минус секунды», а сбитые часы вызывающего
        // (например, отметка из прошлого процесса). Молчим, а не показываем чушь.
        if (elapsedMs < MIN_VISIBLE_MS) return null
        return (elapsedMs / 1_000L).coerceAtMost(MAX_SHOWN_SECONDS)
    }
}
